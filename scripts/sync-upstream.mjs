import { createHash } from "node:crypto";
import { cp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = dirname(SCRIPT_DIR);
const SITE = new URL("https://docs.stencil.so/tern/");
const CACHE = join(ROOT, ".cache", "tern-upstream");
const SNAPSHOT = join(CACHE, "snapshot");
const CURRENT_MANIFEST = join(CACHE, "current-manifest.json");
const BASELINE = join(ROOT, "upstream-baseline.json");
const mode = process.argv[2] ?? "check";

function normalizePageUrl(raw, parent = SITE) {
  const url = new URL(raw, parent);
  url.hash = "";
  if (url.origin !== SITE.origin || !url.pathname.startsWith(SITE.pathname)) return null;
  if (url.pathname.endsWith("/")) url.pathname += "index.md";
  else if (url.pathname.endsWith(".html")) url.pathname = `${url.pathname.slice(0, -5)}.md`;
  else if (!url.pathname.endsWith(".md")) return null;
  return url;
}

function extractAssets(markdown, pageUrl) {
  const assets = new Set();
  const add = (raw) => {
    const url = new URL(raw, pageUrl);
    if (url.origin === SITE.origin && url.pathname.startsWith(SITE.pathname) && /\.(?:avif|gif|jpe?g|png|svg|webp)$/i.test(url.pathname)) {
      url.hash = "";
      assets.add(url.href);
    }
  };
  for (const match of markdown.matchAll(/!\[[^\]]*\]\((<[^>]+>|[^\s)]+)(?:\s+[^)]*)?\)/g)) {
    add(match[1].replace(/^<|>$/g, ""));
  }
  for (const match of markdown.matchAll(/\bsrc=["']([^"']+)["']/gi)) {
    if (!match[1].endsWith(".md") && !match[1].includes("#")) add(match[1]);
  }
  for (const match of markdown.matchAll(/\bsrcset=["']([^"']+)["']/gi)) {
    for (const item of match[1].split(",")) add(item.trim().split(/\s+/)[0]);
  }
  return [...assets].sort();
}

function extractLinks(markdown, pageUrl) {
  const found = new Set();
  const patterns = [
    /!?\[[^\]]*\]\((<[^>]+>|[^\s)]+)(?:\s+[^)]*)?\)/g,
    /<img\b[^>]*\bsrc=["']([^"']+)["']/gi,
  ];
  for (const pattern of patterns) {
    for (const match of markdown.matchAll(pattern)) {
      const href = match[1].replace(/^<|>$/g, "");
      const page = normalizePageUrl(href, pageUrl);
      if (page) found.add(page.href);
    }
  }
  return found;
}

function sha256(data) {
  return createHash("sha256").update(data).digest("hex");
}

function relativePagePath(url) {
  const path = decodeURIComponent(new URL(url).pathname.slice(SITE.pathname.length));
  return path.replaceAll("/", sep);
}

async function loadBaseline() {
  try {
    return JSON.parse(await readFile(BASELINE, "utf8"));
  } catch (error) {
    if (error.code === "ENOENT") return {};
    throw error;
  }
}

async function loadCurrentManifest() {
  try {
    return JSON.parse(await readFile(CURRENT_MANIFEST, "utf8"));
  } catch (error) {
    if (error.code === "ENOENT") return {};
    throw error;
  }
}

async function main() {
  if (mode === "assets") {
    const pageMap = JSON.parse(await readFile(join(ROOT, "upstream-pages.json"), "utf8"));
    const assets = new Set(Object.values(pageMap).flatMap((entry) => entry.assets ?? []));
    let downloaded = 0;
    for (const asset of assets) {
      const url = new URL(asset);
      if (url.origin !== SITE.origin || !url.pathname.startsWith(SITE.pathname)) {
        throw new Error(`Asset is outside the upstream site: ${asset}`);
      }
      const response = await fetch(url);
      if (!response.ok) throw new Error(`${response.status} ${response.statusText}: ${asset}`);
      const data = Buffer.from(await response.arrayBuffer());
      if (!data.length) throw new Error(`Empty image response: ${asset}`);
      const target = join(ROOT, "docs", "assets", relativePagePath(url));
      await mkdir(dirname(target), { recursive: true });
      await writeFile(target, data);
      downloaded++;
    }
    console.log(`Downloaded ${downloaded} images to docs/assets.`);
    return;
  }
  if (mode === "export-source") {
    const sourceDir = join(ROOT, "translation-source");
    const markerPath = join(sourceDir, ".tern-generated");
    const marker = "Generated by scripts/sync-upstream.mjs. Safe to replace as a temporary source snapshot.";
    let owned = false;
    try {
      owned = (await readFile(markerPath, "utf8")) === marker;
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
      try {
        await readdir(sourceDir);
        throw new Error("Refusing to replace translation-source without its ownership marker.");
      } catch (directoryError) {
        if (directoryError.code !== "ENOENT") throw directoryError;
      }
    }
    if (owned) await rm(sourceDir, { recursive: true, force: true });
    await cp(SNAPSHOT, sourceDir, { recursive: true });
    await writeFile(markerPath, marker);
    console.log(`Exported source snapshot to ${relative(ROOT, sourceDir)}`);
    return;
  }
  if (!["check", "accept"].includes(mode)) {
    throw new Error("Usage: node scripts/sync-upstream.mjs [check|accept|export-source|assets]");
  }
  const baseline = await loadBaseline();
  const previous = Object.keys(baseline).length ? baseline : await loadCurrentManifest();
  const queue = [new URL("index.md", SITE).href];
  const seen = new Set();
  const records = {};
  await mkdir(SNAPSHOT, { recursive: true });

  while (queue.length) {
    const url = queue.shift();
    if (seen.has(url)) continue;
    seen.add(url);
    const response = await fetch(url, { headers: { accept: "text/markdown, text/plain" } });
    if (!response.ok) throw new Error(`${response.status} ${response.statusText}: ${url}`);
    const text = await response.text();
    if (!text.trim()) throw new Error(`Empty Markdown response: ${url}`);
    const path = relativePagePath(url);
    const target = join(SNAPSHOT, path);
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, text, "utf8");
    const key = path.replaceAll(sep, "/");
    records[key] = {
      url,
      title: text.match(/^#\s+(.+)$/m)?.[1] ?? "",
      sha256: sha256(text),
      links: [...extractLinks(text, new URL(url))].sort(),
      assets: extractAssets(text, new URL(url)),
    };
    for (const next of records[path.replaceAll(sep, "/")].links) {
      if (!seen.has(next)) queue.push(next);
    }
  }

  const pageMap = Object.fromEntries(Object.entries(records).map(([path, record]) => [path, {
    title: record.title,
    source: record.url,
    translated: `docs/${path}`,
    assets: record.assets,
  }]));
  const pageMapPath = join(ROOT, "upstream-pages.json");
  await writeFile(pageMapPath, `${JSON.stringify(pageMap, null, 2)}\n`);

  const currentPath = CURRENT_MANIFEST;
  await writeFile(currentPath, `${JSON.stringify(records, null, 2)}\n`);
  const currentPaths = Object.keys(records).sort();
  const previousPaths = Object.keys(previous).sort();
  const added = currentPaths.filter((path) => !(path in previous));
  const removed = previousPaths.filter((path) => !(path in records));
  const changed = currentPaths.filter((path) => previous[path] && previous[path].sha256 !== records[path].sha256);

  console.log(`Fetched ${currentPaths.length} Markdown pages from ${SITE.href}`);
  console.log(`Snapshot: ${relative(ROOT, SNAPSHOT)}`);
  console.log(`Manifest: ${relative(ROOT, currentPath)}`);
  if (!Object.keys(baseline).length && previousPaths.length) {
    console.log("No accepted baseline yet; comparing against the previous cached fetch.");
  }
  if (!previousPaths.length) console.log("No baseline yet; review the fetched pages, then run npm run sync:accept.");
  else {
    for (const [label, paths] of [["NEW", added], ["CHANGED", changed], ["REMOVED", removed]]) {
      for (const path of paths) console.log(`${label} ${path}`);
    }
    if (!added.length && !changed.length && !removed.length) console.log("upstream docs unchanged");
  }
  if (mode === "check" && previousPaths.length && (added.length || changed.length || removed.length)) {
    console.error("Upstream documentation changed; translate and verify the diff before accepting a new baseline.");
    process.exitCode = 1;
  }
  if (mode === "accept") {
    await writeFile(BASELINE, `${JSON.stringify(records, null, 2)}\n`);
    console.log(`Accepted baseline: ${relative(ROOT, BASELINE)}`);
  }
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
